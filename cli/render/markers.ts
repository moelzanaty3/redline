import { RedlineError } from '../core/errors.ts';

// Matched on this prefix alone, never on the whole BEGIN line. The rest of the
// line is attribution prose, and prose gets corrected: blocks written by older
// CLI versions are already on disk in every onboarded repository, and matching
// the full literal would stop recognising them the moment the wording changed —
// so the next run would append a second block beside the first instead of
// replacing it.
export const BEGIN_PREFIX = '<!-- REDLINE:BEGIN';
export const BEGIN = `${BEGIN_PREFIX} — generated by Redline. Do not edit inside this block. -->`;
export const END = '<!-- REDLINE:END -->';

export interface MarkerSpan {
  start: number;
  stop: number;
}

// A marker counts only when it opens a line and is not inside a fenced code
// block. Both conditions exist because the block is spliced by byte offset:
// a marker quoted in prose or illustrated in a ```md fence would otherwise be
// the splice point, and everything between it and the next END would be
// deleted. Anchoring alone is not enough — a fence is exactly where a document
// puts a marker on a line of its own to show what one looks like.
function scanMarkers(text: string): { begins: number[]; ends: number[] } {
  const begins: number[] = [];
  const ends: number[] = [];
  let offset = 0;
  let fence: { char: string; length: number } | null = null;

  for (const line of text.split('\n')) {
    const bare = line.endsWith('\r') ? line.slice(0, -1) : line;
    // CommonMark: a fence may be indented up to three spaces, and a closing
    // fence must use the same character and be at least as long as the opening.
    const fenced = /^ {0,3}(`{3,}|~{3,})/.exec(bare);
    const rail = fenced?.[1];
    if (rail !== undefined) {
      const char = rail.slice(0, 1);
      if (fence === null) fence = { char, length: rail.length };
      else if (char === fence.char && rail.length >= fence.length) fence = null;
    } else if (fence === null) {
      if (bare.startsWith(BEGIN_PREFIX)) begins.push(offset);
      else if (bare.startsWith(END)) ends.push(offset);
    }
    offset += line.length + 1;
  }
  return { begins, ends };
}

function refuse(label: string, problem: string): never {
  throw new RedlineError(
    'failed',
    `${label} ${problem}, so Redline cannot tell which part of it is its own and will not write to it`,
    'Restore a single REDLINE:BEGIN … REDLINE:END pair around the generated block, or delete both ' +
      'marker lines and let the next run append a fresh block below your content. Redline made no ' +
      'change to that file.'
  );
}

// The span Redline owns, or null when the file carries no markers at all.
// Anything in between — one marker without its pair, a pair in the wrong order,
// or more than one of either — is a file Redline must not guess about: the
// slice arithmetic would duplicate the span on every run, or delete every byte
// between a stray marker and the real block.
export function findBlock(existing: string, label: string): MarkerSpan | null {
  const { begins, ends } = scanMarkers(existing);
  if (begins.length === 0 && ends.length === 0) return null;
  if (begins.length > 1 || ends.length > 1) {
    refuse(label, `has ${begins.length} REDLINE:BEGIN and ${ends.length} REDLINE:END markers where exactly one of each is expected`);
  }
  const start = begins[0];
  const stop = ends[0];
  if (start === undefined) refuse(label, 'has a REDLINE:END marker with no matching REDLINE:BEGIN');
  if (stop === undefined) refuse(label, 'has a REDLINE:BEGIN marker with no matching REDLINE:END');
  if (stop < start) refuse(label, 'has its REDLINE:END marker before its REDLINE:BEGIN marker');
  return { start, stop };
}

export function wrapBlock(existing: string | null, body: string, label: string): string {
  const block = `${BEGIN}\n\n${body.trimEnd()}\n\n${END}\n`;
  if (existing === null || existing === '') return block;
  const span = findBlock(existing, label);
  if (span === null) {
    // Byte-for-byte on the existing content: only the separator that makes the
    // appended block a paragraph of its own is added. Trimming the human's
    // trailing whitespace would be a change Redline was not asked to make.
    const gap = existing.endsWith('\n\n') ? '' : existing.endsWith('\n') ? '\n' : '\n\n';
    return `${existing}${gap}${block}`;
  }
  return existing.slice(0, span.start) + block.trimEnd() + existing.slice(span.stop + END.length);
}
